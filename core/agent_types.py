"""Structured types for agent reasoning and tool execution."""
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional
from uuid import uuid4


class IntentKind(str, Enum):
    """Classification of user intent."""
    CONVERSATION = "conversation"
    EXPLANATION = "explanation"
    CALCULATION = "calculation"
    SYSTEM_INFO = "system_info"
    PROCESS_QUERY = "process_query"
    FILE_OPERATION = "file_operation"
    NETWORK_QUERY = "network_query"
    DEVELOPMENT = "development"
    DEBUGGING = "debugging"
    GIT_LOCAL = "git_local"
    GITHUB_SEARCH = "github_search"
    STACK_OVERFLOW = "stack_overflow"
    DOCUMENTATION = "documentation"
    CYBERSECURITY = "cybersecurity"
    SERVICE_ADMIN = "service_admin"
    TRANSLATION = "translation"
    WEB_SEARCH = "web_search"
    AMBIGUOUS = "ambiguous"
    UNKNOWN = "unknown"


@dataclass
class Intent:
    """Classified user intent with confidence."""
    kind: IntentKind
    confidence: float  # 0.0 to 1.0
    reasoning: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class ToolCall:
    """Validated tool invocation."""
    tool_name: str
    capability: str
    arguments: dict[str, Any] = field(default_factory=dict)
    requires_confirmation: bool = False
    risk_level: str = "read_only"  # read_only, low, moderate, high, destructive
    timeout: float = 20.0
    id: str = field(default_factory=lambda: uuid4().hex[:12])


@dataclass
class ToolResult:
    """Result from tool execution."""
    tool_call_id: str
    success: bool
    data: dict[str, Any] = field(default_factory=dict)
    error: str | None = None
    error_category: str | None = None
    duration: float = 0.0
    stdout: str = ""
    stderr: str = ""
    exit_code: int | None = None


@dataclass
class SourceReference:
    """Reference to an external source."""
    source_type: str  # "github", "stack_overflow", "documentation", "web"
    title: str
    url: str
    snippet: str = ""
    relevance: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)
    retrieved_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


@dataclass
class ExecutionContext:
    """Context for agent reasoning."""
    request: str
    conversation_history: list[dict[str, Any]] = field(default_factory=list)
    last_results: list[ToolResult] = field(default_factory=list)
    last_tool_calls: list[ToolCall] = field(default_factory=list)
    entities: dict[str, Any] = field(default_factory=dict)
    offline_mode: bool = False
    llm_available: bool = False
    current_directory: str = ""
    git_repository: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class AgentPlan:
    """Plan generated by the agent."""
    intent: Intent
    tool_calls: list[ToolCall] = field(default_factory=list)
    direct_answer: str | None = None
    needs_clarification: str | None = None
    reasoning: str = ""
    estimated_duration: float = 0.0
    requires_internet: bool = False
    sources_to_consult: list[SourceReference] = field(default_factory=list)


@dataclass
class AgentResponse:
    """Final response from the agent."""
    request: str
    intent: Intent
    message: str
    tool_results: list[ToolResult] = field(default_factory=list)
    sources: list[SourceReference] = field(default_factory=list)
    reasoning_method: str = "rules"  # rules, local_model, hybrid
    confidence: float = 1.0
    metadata: dict[str, Any] = field(default_factory=dict)
    error: str | None = None
    error_category: str | None = None
